-- Isolated test copy of the production noirxu_ai schema (Loki), reconstructed from the
-- live catalog on 2026-10-23: same tables, constraints, indexes, RLS policies and the
-- same limited noirxu_ai_app role. For local integration tests only — never run on Loki.

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'noirxu_ai_app') then
    create role noirxu_ai_app login password 'test-only-password' nosuperuser nocreatedb nocreaterole nobypassrls connection limit 10;
  end if;
end $$;

create schema if not exists noirxu_ai;
revoke all on schema noirxu_ai from public;
grant usage on schema noirxu_ai to noirxu_ai_app;
alter role noirxu_ai_app set search_path = noirxu_ai;

create table noirxu_ai.agenda_items (
  id uuid primary key, user_id text not null, title text not null check (char_length(title) between 1 and 200),
  notes text not null default '', due_date date, due_time time, importance smallint not null default 2 check (importance between 1 and 3),
  status text not null default 'open' check (status in ('open', 'done', 'cancelled')), source text not null default 'manual',
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index agenda_items_user_open_idx on noirxu_ai.agenda_items (user_id, status, due_date);

create table noirxu_ai.audit_log (
  id bigint generated by default as identity primary key, at timestamptz not null, user_id text not null, tool text not null,
  kind text not null, event text not null, proposal_id uuid, record_id text, error_code text, duration_ms integer
);
create index audit_log_user_at_idx on noirxu_ai.audit_log (user_id, at desc);

create table noirxu_ai.credentials (
  user_id text not null, connection text not null check (connection in ('ledger', 'journal', 'radar', 'gmail')),
  metadata jsonb not null default '{}', sealed text not null, updated_at timestamptz not null default now(), primary key (user_id, connection)
);

create table noirxu_ai.notification_log (dedupe_key text primary key, user_id text not null, kind text not null, sent_at timestamptz not null default now());

create table noirxu_ai.proposals (
  id uuid primary key, user_id text not null, tool text not null,
  status text not null check (status in ('pending', 'executing', 'succeeded', 'failed', 'outcome_unknown', 'rejected')),
  doc jsonb not null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index proposals_user_created_idx on noirxu_ai.proposals (user_id, created_at desc);

create table noirxu_ai.push_subscriptions (
  endpoint text primary key, user_id text not null, subscription jsonb not null, user_agent text not null default '',
  created_at timestamptz not null default now(), last_success_at timestamptz
);

create table noirxu_ai.reminders (
  id uuid primary key, item_id uuid not null references noirxu_ai.agenda_items(id) on delete cascade, user_id text not null,
  remind_at timestamptz not null, label text not null, sent_at timestamptz
);
create index reminders_due_idx on noirxu_ai.reminders (remind_at) where sent_at is null;

create table noirxu_ai.settings (key text primary key, sealed text not null, updated_at timestamptz not null default now());

-- Same privilege set as production.
grant select, insert, update, delete on noirxu_ai.agenda_items, noirxu_ai.credentials, noirxu_ai.proposals, noirxu_ai.push_subscriptions, noirxu_ai.reminders to noirxu_ai_app;
grant select, insert on noirxu_ai.audit_log, noirxu_ai.notification_log to noirxu_ai_app;
grant select, insert, update on noirxu_ai.settings to noirxu_ai_app;
grant usage on sequence noirxu_ai.audit_log_id_seq to noirxu_ai_app;

do $$ declare t text; begin
  foreach t in array array['agenda_items', 'audit_log', 'credentials', 'notification_log', 'proposals', 'push_subscriptions', 'reminders', 'settings'] loop
    execute format('alter table noirxu_ai.%I enable row level security', t);
    execute format('create policy noirxu_ai_app_%s on noirxu_ai.%I for all to noirxu_ai_app using (true) with check (true)', t, t);
  end loop;
end $$;

